/**
 * Rendering: the mermaid knowledge map and the JSON index the web hub reads.
 *
 * The map is not decoration. Forcing the plan into an explicit DAG is what
 * stops a tutor from winging it — it has to commit to an ordering before it
 * teaches, and the learner gets to see what is coming.
 */

import { MASTERY_THRESHOLD, masteryLabel } from "./bkt.mjs";
import { masteryOf, summarize, topoSort } from "./graph.mjs";

/** Mermaid node ids must be identifier-safe. */
function nodeId(id) {
  return `n_${String(id).replace(/[^A-Za-z0-9_]/g, "_")}`;
}

function escapeLabel(text) {
  return String(text).replace(/"/g, "'").replace(/[\r\n]+/g, " ");
}

const CLASS_DEFS = [
  "classDef mastered fill:#dcfce7,stroke:#16a34a,stroke-width:1px,color:#14532d;",
  "classDef solid fill:#e0f2fe,stroke:#0284c7,stroke-width:1px,color:#0c4a6e;",
  "classDef shaky fill:#fef9c3,stroke:#ca8a04,stroke-width:1px,color:#713f12;",
  "classDef weak fill:#ffedd5,stroke:#ea580c,stroke-width:1px,color:#7c2d12;",
  "classDef gap fill:#fee2e2,stroke:#dc2626,stroke-width:1px,color:#7f1d1d;",
  "classDef frontier stroke-width:3px,stroke-dasharray:4 2;",
];

/**
 * Mermaid flowchart of the concept graph, coloured by mastery.
 * `highlight` receives a dashed border — used to mark the frontier.
 */
export function renderMermaid(graph, model, options = {}) {
  const { highlight = new Set(), direction = "TD", scope = null } = options;
  const ids = scope
    ? [...graph.nodes.keys()].filter((id) => scope.has(id))
    : [...graph.nodes.keys()];

  if (ids.length === 0) {
    return "```mermaid\nflowchart TD\n  empty[\"No concepts yet\"]\n```";
  }

  const { order } = topoSort(graph, ids);
  const ordered = order.length === ids.length ? order : ids.slice().sort();

  const lines = [`flowchart ${direction}`];
  const classed = { mastered: [], solid: [], shaky: [], weak: [], gap: [] };

  for (const id of ordered) {
    const node = graph.nodes.get(id);
    const pL = masteryOf(model, id);
    const label = escapeLabel(node.title ?? id);
    const pct = Math.round(pL * 100);
    lines.push(`  ${nodeId(id)}["${label}<br/><small>${pct}%</small>"]`);
    classed[masteryLabel(pL)].push(nodeId(id));
  }

  for (const id of ordered) {
    const node = graph.nodes.get(id);
    for (const dep of node.requires) {
      if (!graph.nodes.has(dep)) continue;
      if (scope && !scope.has(dep)) continue;
      lines.push(`  ${nodeId(dep)} --> ${nodeId(id)}`);
    }
    // Background reads as a dotted arrow: it orders the plan without gating it.
    for (const dep of node.assumes ?? []) {
      if (!graph.nodes.has(dep)) continue;
      if (scope && !scope.has(dep)) continue;
      lines.push(`  ${nodeId(dep)} -.-> ${nodeId(id)}`);
    }
  }

  lines.push("");
  for (const def of CLASS_DEFS) lines.push(`  ${def}`);
  for (const [name, members] of Object.entries(classed)) {
    if (members.length > 0) lines.push(`  class ${members.join(",")} ${name};`);
  }
  const marked = [...highlight].filter((id) => graph.nodes.has(id));
  if (marked.length > 0) {
    lines.push(`  class ${marked.map(nodeId).join(",")} frontier;`);
  }

  return `\`\`\`mermaid\n${lines.join("\n")}\n\`\`\``;
}

/** The full `learn/map.md` document. */
export function renderMapDocument(graph, model, frontierList) {
  const stats = summarize(graph, model);
  const highlight = new Set(frontierList.map((f) => f.id));
  const generated = new Date().toISOString();

  const frontierLines =
    frontierList.length > 0
      ? frontierList
          .slice(0, 12)
          .map(
            (f) =>
              `- [[${f.id}]] — ${f.title} · ${Math.round(f.pL * 100)}% (${masteryLabel(f.pL)})`,
          )
          .join("\n")
      : "- Nothing at the frontier. Add concepts, or every prerequisite is still unmet.";

  return `---
title: Knowledge Map
generated: ${generated}
concepts: ${stats.total}
mastered: ${stats.mastered}
---

# Knowledge Map

> Generated by \`npm run learn -- map\`. Do not edit by hand — edits are overwritten.

**${stats.mastered} mastered · ${stats.learning} in progress · ${stats.untouched} untouched · ${stats.total} total**

Mastery is p(L) from Bayesian Knowledge Tracing: the probability you hold a
concept, given every answer you have given. ${Math.round(MASTERY_THRESHOLD * 100)}% counts as mastered.

## The frontier

The edge of your understanding — every prerequisite met, the concept itself
not yet held. This is the only place teaching is efficient.

${frontierLines}

## Graph

${renderMermaid(graph, model, { highlight })}

## Legend

| Colour | Meaning | p(L) |
| --- | --- | --- |
| green | mastered | ≥ 95% |
| blue | solid | 75–95% |
| yellow | shaky | 55–75% |
| orange | weak | 40–55% |
| red | gap | ≤ 40% |

A dashed border marks a frontier concept. A solid arrow is a hard
prerequisite that gates teaching and carries evidence; a dotted arrow is
background that only affects ordering.
`;
}

/**
 * Machine-readable snapshot for the web hub. Written to
 * learn/state/index.json so the Next.js build reads exactly one file
 * instead of re-parsing the whole vault.
 */
export function buildIndex(graph, model, reviews, frontierList) {
  const concepts = [...graph.nodes.values()].map((node) => {
    const pL = masteryOf(model, node.id);
    const entry = model.concepts?.[node.id];
    const card = reviews.cards?.[node.id];
    return {
      id: node.id,
      title: node.title ?? node.id,
      summary: node.summary ?? "",
      tags: node.tags ?? [],
      requires: node.requires ?? [],
      assumes: node.assumes ?? [],
      pL,
      mastery: masteryLabel(pL),
      observations: entry?.observations ?? 0,
      correct: entry?.correct ?? 0,
      lastSeen: entry?.lastSeen ?? null,
      due: card?.due ?? null,
      lapses: card?.lapses ?? 0,
      leech: Boolean(card?.leech),
      sources: node.sources ?? [],
      topics: node.topics ?? [],
      openQuestions: node.openQuestions ?? [],
    };
  });

  concepts.sort((a, b) => a.title.localeCompare(b.title));

  return {
    version: 1,
    generatedAt: new Date().toISOString(),
    stats: summarize(graph, model),
    frontier: frontierList.map((f) => f.id),
    concepts,
    edges: [...graph.nodes.values()].flatMap((node) => [
      ...(node.requires ?? [])
        .filter((dep) => graph.nodes.has(dep))
        .map((dep) => ({ from: dep, to: node.id, kind: "requires" })),
      ...(node.assumes ?? [])
        .filter((dep) => graph.nodes.has(dep))
        .map((dep) => ({ from: dep, to: node.id, kind: "assumes" })),
    ]),
    mermaid: renderMermaid(graph, model, {
      highlight: new Set(frontierList.map((f) => f.id)),
    }),
  };
}
